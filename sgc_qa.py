    def initialZoom(self):
        canvas = self.iface.mapCanvas()
        scale = self.dataLayers["initial_zoom"]["scale"]
        x = self.dataLayers["initial_zoom"]["x"]
        y = self.dataLayers["initial_zoom"]["y"]
